/*
 * Vendor jszip + epub.js into the app bundle (eng review 4A).
 *
 * Until now readerHtml.ts loaded both from cdnjs at WebView startup, so
 * reading (and the import extractor) failed offline. This script fetches
 * pinned versions once and wraps them as TS modules exporting the raw
 * source, which epubShell.ts inlines into generated WebView HTML.
 *
 * Run on upgrade only:  node scripts/vendor-reader-libs.js
 * Output is committed — builds never need the network.
 */

const fs = require("fs");
const path = require("path");

const LIBS = [
  {
    name: "jszip",
    version: "3.10.1",
    url: "https://cdnjs.cloudflare.com/ajax/libs/jszip/3.10.1/jszip.min.js",
    out: "jszipMin.ts",
    marker: "JSZip",
  },
  {
    name: "epub.js",
    version: "0.3.93",
    url: "https://cdnjs.cloudflare.com/ajax/libs/epub.js/0.3.93/epub.min.js",
    out: "epubjsMin.ts",
    marker: "ePub",
  },
];

const OUT_DIR = path.join(__dirname, "..", "features", "reader", "vendor");

async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const lib of LIBS) {
    process.stdout.write(`fetching ${lib.name}@${lib.version}... `);
    const res = await fetch(lib.url);
    if (!res.ok) throw new Error(`${lib.url} -> HTTP ${res.status}`);
    let code = await res.text();
    if (!code.includes(lib.marker)) {
      throw new Error(`${lib.name}: marker "${lib.marker}" not found — wrong payload?`);
    }
    // Guard the inline <script> context: a literal "</script" inside the
    // code would terminate the tag early. "<\/" is identical to "</"
    // inside JS strings, so behavior is unchanged.
    code = code.replace(/<\/script/gi, "<\\/script");
    const banner =
      `/* AUTO-GENERATED by scripts/vendor-reader-libs.js — do not edit.\n` +
      ` * ${lib.name}@${lib.version} from ${lib.url}\n */\n` +
      `/* eslint-disable */\n`;
    const body = `export default ${JSON.stringify(code)};\n`;
    fs.writeFileSync(path.join(OUT_DIR, lib.out), banner + body);
    console.log(`${(code.length / 1024).toFixed(0)}KB -> features/reader/vendor/${lib.out}`);
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
